static const int dimensione_database_aperture =
    sizeof(database_aperture) / sizeof(database_aperture[0]);

// ─────────────────────────────────────────────────────────────────────────────
std::pair<int, int> cerca_nel_book() {
    // numero_mosse = 2 × semimossse nella sequenza → confronta con storia_mosse.size()
    int n = (int)storia_mosse.size();

    Mossa mosse_legali_book[256];
    int numero_legali = genera_mosse(mosse_legali_book, turno, b);

    std::pair<int,int> candidati[64];
    int num_candidati = 0;

    for (int i = 0; i < dimensione_database_aperture && num_candidati < 64; i++) {
        const EntrataApertura &e = database_aperture[i];
        if (e.numero_mosse / 2 != n) continue;

        bool ok = true;
        for (int j = 0; j < n && ok; j++) {
            if (storia_mosse[j].idx  != e.sequenza[j * 2] ||
                storia_mosse[j].idx2 != e.sequenza[j * 2 + 1])
                ok = false;
        }
        if (!ok) continue;

        // Verifica legalità della risposta
        for (int k = 0; k < numero_legali; k++) {
            if (mosse_legali_book[k].da == e.risposta_da &&
                mosse_legali_book[k].a  == e.risposta_a) {
                candidati[num_candidati++] = {e.risposta_da, e.risposta_a};
                break;
            }
        }
    }

    if (num_candidati == 0) return {-1, -1};
    return candidati[rand() % num_candidati];
}
